"""
WCFFBP
CMS Original Medicare Containment Evidence Digest v0.1

PURPOSE
-------
Create a compact, human-reviewable digest from the already-extracted
CMS Original Medicare Geographic Variation documentation.

This script answers only evidence-location questions:

    1. What does CMS say about TOT_MDCR_PYMT_AMT?
    2. What does CMS say about the FFS / claims source universe?
    3. What does CMS say about ACOs in this methodology?
    4. What relevant payment / expenditure language appears?
    5. Is the evidence sufficient to proceed to a formal
       MSSP-versus-FFS economic-overlap reconciliation?

It DOES NOT determine that MSSP EarnSaveLoss is economically additive.
It DOES NOT establish Washington payment-dollar incidence.
It DOES NOT write to the database or ledger.

The console output is intentionally short.
"""


# =====================================================================
# HELPERS
# =====================================================================

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()

    with path.open("rb") as handle:
        while True:
            block = handle.read(1024 * 1024)

            if not block:
                break

            h.update(block)

    return h.hexdigest().upper()


def normalize_whitespace(text: str) -> str:
    text = text.replace("\x00", " ")

    text = re.sub(
        r"\s+",
        " ",
        text,
    )

    return text.strip()


def parse_page_text_file(
    path: Path,
) -> dict[int, str]:
    """
    Parse the page-delimited text generated by the v0.1 extractor.

    Expected structure:

        [PAGE 1]
        ------
        text...

        [PAGE 2]
        ------
        text...
    """

    raw = path.read_text(
        encoding="utf-8",
    )

    page_pattern = re.compile(
        r"\[PAGE\s+(\d+)\]\s*\n-+\s*\n",
        flags=re.IGNORECASE,
    )

    matches = list(
        page_pattern.finditer(
            raw
        )
    )

    pages = {}

    for index, match in enumerate(
        matches
    ):
        page_number = int(
            match.group(1)
        )

        start = match.end()

        if index + 1 < len(matches):
            end = matches[
                index + 1
            ].start()

        else:
            end = len(
                raw
            )

        page_text = raw[
            start:end
        ]

        pages[
            page_number
        ] = normalize_whitespace(
            page_text
        )

    return pages


def page_matches_patterns(
    text: str,
    patterns: list[str],
) -> list[str]:
    hits = []

    for pattern in patterns:
        if re.search(
            pattern,
            text,
            flags=re.IGNORECASE,
        ):
            hits.append(
                pattern
            )

    return hits


def score_page(
    text: str,
    patterns: list[str],
) -> int:
    score = 0

    for pattern in patterns:
        matches = re.findall(
            pattern,
            text,
            flags=re.IGNORECASE,
        )

        score += len(
            matches
        )

    return score


def sentence_split(
    text: str,
) -> list[str]:
    """
    Conservative sentence splitter suitable for extracted PDF prose.
    """

    text = normalize_whitespace(
        text
    )

    sentences = re.split(
        r"(?<=[.!?])\s+(?=[A-Z0-9(])",
        text,
    )

    return [
        sentence.strip()
        for sentence in sentences
        if sentence.strip()
    ]


def relevant_sentence_window(
    text: str,
    patterns: list[str],
    *,
    radius: int = 1,
) -> str:
    """
    Keep matching sentences plus one sentence before/after.

    This is much smaller than dumping an entire PDF page.
    """

    sentences = sentence_split(
        text
    )

    matching_indexes = []

    for index, sentence in enumerate(
        sentences
    ):
        if any(
            re.search(
                pattern,
                sentence,
                flags=re.IGNORECASE,
            )
            for pattern in patterns
        ):
            matching_indexes.append(
                index
            )

    if not matching_indexes:
        return ""

    keep_indexes = set()

    for index in matching_indexes:
        for offset in range(
            -radius,
            radius + 1,
        ):
            candidate = (
                index
                + offset
            )

            if (
                0
                <= candidate
                < len(sentences)
            ):
                keep_indexes.add(
                    candidate
                )

    selected = [
        sentences[index]
        for index in sorted(
            keep_indexes
        )
    ]

    return normalize_whitespace(
        " ".join(
            selected
        )
    )


def deduplicate_passages(
    passages: list[dict],
) -> list[dict]:
    """
    Remove exact normalized duplicate passages while retaining the
    first page reference.
    """

    seen = set()
    unique = []

    for passage in passages:
        normalized = normalize_whitespace(
            passage[
                "text"
            ]
        ).casefold()

        if not normalized:
            continue

        if normalized in seen:
            continue

        seen.add(
            normalized
        )

        unique.append(
            passage
        )

    return unique


# =====================================================================
# MAIN
# =====================================================================

def main() -> int:
    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    checks = []

    def check(
        description: str,
        passed: bool,
        detail: str,
    ) -> None:
        checks.append(
            {
                "description": description,
                "status": (
                    "PASS"
                    if passed
                    else "FAIL"
                ),
                "detail": detail,
            }
        )

    # -----------------------------------------------------------------
    # INPUT CHECKS
    # -----------------------------------------------------------------

    dictionary_exists = (
        DICTIONARY_TEXT.exists()
    )

    methods_exists = (
        METHODS_TEXT.exists()
    )

    check(
        "Extracted dictionary text exists",
        dictionary_exists,
        str(
            DICTIONARY_TEXT.relative_to(
                REPO_ROOT
            )
        ),
    )

    check(
        "Extracted Methods Paper text exists",
        methods_exists,
        str(
            METHODS_TEXT.relative_to(
                REPO_ROOT
            )
        ),
    )

    if not (
        dictionary_exists
        and methods_exists
    ):
        print(
            "FAIL: required v0.1 extracted-text artifact is missing."
        )

        return 1

    # -----------------------------------------------------------------
    # PARSE PAGE TEXT
    # -----------------------------------------------------------------

    dictionary_pages = (
        parse_page_text_file(
            DICTIONARY_TEXT
        )
    )

    methods_pages = (
        parse_page_text_file(
            METHODS_TEXT
        )
    )

    check(
        "Dictionary page structure parsed",
        len(
            dictionary_pages
        )
        == 14,
        (
            f"{len(dictionary_pages)} page(s)"
        ),
    )

    check(
        "Methods Paper page structure parsed",
        len(
            methods_pages
        )
        == 13,
        (
            f"{len(methods_pages)} page(s)"
        ),
    )

    source_map = {
        "dictionary": dictionary_pages,
        "methods": methods_pages,
    }

    # -----------------------------------------------------------------
    # BUILD DIGEST
    # -----------------------------------------------------------------

    digest_sections = []

    concept_results = {}

    for concept in CONCEPTS:
        pages = source_map[
            concept[
                "source"
            ]
        ]

        ranked_pages = []

        for page_number, text in pages.items():
            hits = page_matches_patterns(
                text,
                concept[
                    "patterns"
                ],
            )

            if not hits:
                continue

            score = score_page(
                text,
                concept[
                    "patterns"
                ],
            )

            passage = relevant_sentence_window(
                text,
                concept[
                    "patterns"
                ],
                radius=1,
            )

            if not passage:
                continue

            ranked_pages.append(
                {
                    "page": page_number,
                    "score": score,
                    "text": passage,
                }
            )

        ranked_pages.sort(
            key=lambda row: (
                -row[
                    "score"
                ],
                row[
                    "page"
                ],
            )
        )

        unique_passages = (
            deduplicate_passages(
                ranked_pages
            )
        )

        selected = unique_passages[
            : concept[
                "max_pages"
            ]
        ]

        concept_results[
            concept[
                "name"
            ]
        ] = selected

        check(
            (
                f"Evidence located for "
                f"{concept['name']}"
            ),
            len(
                selected
            )
            > 0,
            (
                f"{len(selected)} compact "
                "passage(s)"
            ),
        )

    # -----------------------------------------------------------------
    # SPECIAL CHECKS
    # -----------------------------------------------------------------

    dictionary_all_text = " ".join(
        dictionary_pages.values()
    )

    methods_all_text = " ".join(
        methods_pages.values()
    )

    tot_present = bool(
        re.search(
            r"\bTOT_MDCR_PYMT_AMT\b",
            dictionary_all_text,
            flags=re.IGNORECASE,
        )
    )

    check(
        "TOT_MDCR_PYMT_AMT remains present in parsed dictionary text",
        tot_present,
        (
            "FOUND"
            if tot_present
            else "NOT FOUND"
        ),
    )

    aco_present = bool(
        re.search(
            (
                r"\bACO\b|"
                r"\bACOs\b|"
                r"Accountable\s+Care\s+Organization"
            ),
            methods_all_text,
            flags=re.IGNORECASE,
        )
    )

    check(
        "ACO terminology remains present in parsed Methods Paper",
        aco_present,
        (
            "FOUND"
            if aco_present
            else "NOT FOUND"
        ),
    )

    claims_present = bool(
        re.search(
            r"\bclaims?\b",
            methods_all_text,
            flags=re.IGNORECASE,
        )
    )

    check(
        "Claims terminology remains present in parsed Methods Paper",
        claims_present,
        (
            "FOUND"
            if claims_present
            else "NOT FOUND"
        ),
    )

    ffs_present = bool(
        re.search(
            (
                r"\bFFS\b|"
                r"fee[- ]for[- ]service"
            ),
            methods_all_text,
            flags=re.IGNORECASE,
        )
    )

    check(
        "FFS terminology remains present in parsed Methods Paper",
        ffs_present,
        (
            "FOUND"
            if ffs_present
            else "NOT FOUND"
        ),
    )

    # -----------------------------------------------------------------
    # RENDER DIGEST
    # -----------------------------------------------------------------

    lines = []

    lines.append(
        "=" * 100
    )

    lines.append(
        "CMS ORIGINAL MEDICARE CONTAINMENT EVIDENCE DIGEST v0.1"
    )

    lines.append(
        "=" * 100
    )

    lines.append("")

    lines.append(
        "BOUNDARY"
    )

    lines.append(
        "-" * 100
    )

    lines.append(
        "Compact review of already-extracted CMS Original Medicare Geographic Variation documentation."
    )

    lines.append(
        "No MSSP/FFS additivity decision is made here."
    )

    lines.append(
        "No Washington payment-dollar incidence is inferred."
    )

    lines.append(
        "No database write or ledger inclusion occurs."
    )

    lines.append("")

    lines.append(
        "INPUT PROVENANCE"
    )

    lines.append(
        "-" * 100
    )

    lines.append(
        "Dictionary extracted-text SHA-256: "
        + sha256_file(
            DICTIONARY_TEXT
        )
    )

    lines.append(
        "Methods extracted-text SHA-256: "
        + sha256_file(
            METHODS_TEXT
        )
    )

    lines.append("")

    # -----------------------------------------------------------------
    # EVIDENCE SECTIONS
    # -----------------------------------------------------------------

    section_number = 1

    for concept in CONCEPTS:
        name = concept[
            "name"
        ]

        passages = concept_results[
            name
        ]

        lines.append(
            f"{section_number}. {name}"
        )

        lines.append(
            "-" * 100
        )

        if not passages:
            lines.append(
                "NOT FOUND"
            )

            lines.append(
                "No substantive conclusion should be drawn from absence alone."
            )

        else:
            for index, passage in enumerate(
                passages,
                start=1,
            ):
                lines.append(
                    (
                        f"[PASSAGE {index} | "
                        f"PDF PAGE {passage['page']} | "
                        f"RELEVANCE SCORE {passage['score']}]"
                    )
                )

                lines.append(
                    passage[
                        "text"
                    ]
                )

                lines.append("")

        lines.append("")

        section_number += 1

    # -----------------------------------------------------------------
    # EVIDENCE STATUS MATRIX
    # -----------------------------------------------------------------

    lines.append(
        "EVIDENCE STATUS MATRIX"
    )

    lines.append(
        "-" * 100
    )

    matrix = [
        (
            "TOT_MDCR_PYMT_AMT definition",
            (
                "FOUND"
                if concept_results[
                    "TOT_MDCR_PYMT_AMT"
                ]
                else "NOT FOUND"
            ),
        ),
        (
            "FFS / claims source-universe evidence",
            (
                "FOUND"
                if concept_results[
                    "FFS / CLAIMS SOURCE UNIVERSE"
                ]
                else "NOT FOUND"
            ),
        ),
        (
            "ACO-related methodology evidence",
            (
                "FOUND"
                if concept_results[
                    "ACO TREATMENT"
                ]
                else "NOT FOUND"
            ),
        ),
        (
            "Payment / expenditure boundary evidence",
            (
                "FOUND"
                if concept_results[
                    "PAYMENT / EXPENDITURE BOUNDARY"
                ]
                else "NOT FOUND"
            ),
        ),
        (
            "MSSP EarnSaveLoss economic additivity",
            "NOT DETERMINED BY THIS ARTIFACT",
        ),
        (
            "Washington payment-dollar incidence",
            "NOT DETERMINED BY THIS ARTIFACT",
        ),
    ]

    for label, status in matrix:
        lines.append(
            f"{label}: {status}"
        )

    lines.append("")

    # -----------------------------------------------------------------
    # CHECKS
    # -----------------------------------------------------------------

    lines.append(
        "CHECKS"
    )

    lines.append(
        "-" * 100
    )

    for item in checks:
        lines.append(
            (
                f"{item['status']} | "
                f"{item['description']} | "
                f"{item['detail']}"
            )
        )

    overall_pass = all(
        item[
            "status"
        ]
        == "PASS"
        for item in checks
    )

    lines.append("")

    lines.append(
        "=" * 100
    )

    lines.append(
        "OVERALL CMS ORIGINAL MEDICARE CONTAINMENT EVIDENCE DIGEST v0.1: "
        + (
            "PASS"
            if overall_pass
            else "FAIL"
        )
    )

    lines.append(
        "=" * 100
    )

    lines.append("")

    lines.append(
        "PASS means the relevant CMS passages were compactly located for human review."
    )

    lines.append(
        "PASS does NOT establish that MSSP EarnSaveLoss is economically distinct from Original Medicare / FFS."
    )

    lines.append(
        "No source is additive by default."
    )

    digest_text = "\n".join(
        lines
    )

    DIGEST_TXT.write_text(
        digest_text,
        encoding="utf-8",
    )

    # -----------------------------------------------------------------
    # SHORT CONSOLE OUTPUT ONLY
    # -----------------------------------------------------------------

    print(
        "=" * 100
    )

    print(
        "CMS ORIGINAL MEDICARE CONTAINMENT EVIDENCE DIGEST v0.1"
    )

    print(
        "=" * 100
    )

    print(
        f"Dictionary pages parsed: {len(dictionary_pages)}"
    )

    print(
        f"Methods pages parsed: {len(methods_pages)}"
    )

    print("")

    for concept in CONCEPTS:
        name = concept[
            "name"
        ]

        passages = concept_results[
            name
        ]

        page_numbers = [
            str(
                row[
                    "page"
                ]
            )
            for row in passages
        ]

        print(
            f"{name}: "
            f"{len(passages)} passage(s)"
            + (
                " | pages "
                + ", ".join(
                    page_numbers
                )
                if page_numbers
                else ""
            )
        )

    print("")

    print(
        "OVERALL: "
        + (
            "PASS"
            if overall_pass
            else "FAIL"
        )
    )

    print("")

    print(
        "Compact digest written:"
    )

    print(
        f"  {DIGEST_TXT.relative_to(REPO_ROOT)}"
    )

    print("")

    print(
        "Next: review the compact digest before making any MSSP/FFS additivity decision."
    )

    return (
        0
        if overall_pass
        else 1
    )


if __name__ == "__main__":
    sys.exit(
        main()
    )
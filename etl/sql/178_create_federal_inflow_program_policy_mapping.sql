   SEED OASDI PROGRAM MAPPINGS

   SSA benefit payments are the preferred accounting source.

   USAspending:
       96.001 Disability
       96.002 Retirement
       96.004 Survivors

   are overlapping representations and therefore EXCLUDE_DUPLICATE from the

/*
===============================================================================
MIGRATION 178
ETL-174B-5L
CREATE AND SEED FEDERAL INFLOW PROGRAM -> ACCOUNTING POLICY MAPPING
===============================================================================

PURPOSE
-------
Create an explicit, auditable mapping between a source-system program code
and an established federal inflow source policy.

This resolves an architectural gap identified by ETL-174B-5J and 5K:

    - source-program classifications describe program identity and overlap risk;
    - source policies establish accounting treatment;
    - their inflow_family / inflow_subfamily values are not always identical;
    - therefore accounting treatment must not be inferred by fuzzy or
      family-only joins.

The mapping created here explicitly states which established source policy
governs a particular USAspending Assistance Listing for accounting purposes.

ACCOUNTING RESOLUTION HIERARCHY
-------------------------------
Future assistance accounting resolution will be:

    1. award-specific accounting classification
    2. explicit program -> source-policy mapping
    3. UNCLASSIFIED_REVIEW

Award-specific classification always has precedence.

IMPORTANT
---------
This migration DOES NOT:

    - classify previously unresolved programs;
    - infer mappings from Assistance Listing prefixes;
    - apply broad family-level rules;
    - create a blanket VA 64.* rule;
    - replace CHIP award-level classifications;
    - alter certified assistance transactions;
    - alter authoritative SSA/CMS/VA accounting controls;
    - construct the final federal inflow ledger.

Only previously established accounting decisions are mapped.

SEE
---
ETL-174B-5J
ETL-174B-5K
ETL-135 / ANALYSIS-116-v1
ETL-174B-4B
ETL-174B-5B
ETL-174B-5I / Migration 177
===============================================================================
*/

BEGIN;


/* ============================================================================
   SECTION 1
   CREATE MAPPING TABLE
   ========================================================================== */

CREATE TABLE IF NOT EXISTS reference.federal_inflow_program_policy_mapping (
    federal_inflow_program_policy_mapping_id
        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_system
        text NOT NULL,

    source_program_code
        text NOT NULL,

    federal_inflow_source_policy_id
        bigint NOT NULL
        REFERENCES reference.federal_inflow_source_policy (
            federal_inflow_source_policy_id
        ),

    resolved_accounting_disposition
        text NOT NULL,

    mapping_basis
        text NOT NULL,

    methodology_version
        text NOT NULL,

    valid_from_fiscal_year
        integer,

    valid_through_fiscal_year
        integer,

    created_at
        timestamp without time zone
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at
        timestamp without time zone
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_federal_inflow_program_policy_mapping
        UNIQUE (
            source_system,
            source_program_code,
            methodology_version
        ),

    CONSTRAINT ck_federal_inflow_program_policy_mapping_disposition
        CHECK (
            resolved_accounting_disposition IN (
                'INCLUDE_ADDITIVE',
                'EXCLUDE_DUPLICATE',
                'WITHHOLD_UNRESOLVED',
                'REFERENCE_ONLY'
            )
        ),

    CONSTRAINT ck_federal_inflow_program_policy_mapping_fiscal_year
        CHECK (
               valid_from_fiscal_year IS NULL
            OR valid_through_fiscal_year IS NULL
            OR valid_from_fiscal_year <= valid_through_fiscal_year
        )
);


COMMENT ON TABLE reference.federal_inflow_program_policy_mapping IS
'Explicit mapping from a source-system program code to an established federal '
'inflow source policy and its transaction-level accounting disposition. '
'Used only when no more-specific award accounting classification applies. '
'This table prevents accounting treatment from being inferred through fuzzy '
'or family-only program-policy joins.';


COMMENT ON COLUMN
reference.federal_inflow_program_policy_mapping.resolved_accounting_disposition
IS
'Transaction-level accounting disposition inherited from an explicitly mapped '
'established source policy. Award-specific accounting classification has '
'precedence over this mapping.';



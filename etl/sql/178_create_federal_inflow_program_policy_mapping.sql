INSERT INTO reference.federal_inflow_program_policy_mapping (
    source_system,
    source_program_code,
    federal_inflow_source_policy_id,
    resolved_accounting_disposition,
    mapping_basis,
    methodology_version,
    valid_from_fiscal_year,
    valid_through_fiscal_year
)
SELECT
    'USASPENDING_ASSISTANCE',
    program_code,
    policy.federal_inflow_source_policy_id,
    'EXCLUDE_DUPLICATE',
    'Explicit mapping to the established OASDI accounting policy. SSA benefit '
    || 'payments are the preferred accounting source; USAspending Assistance '
    || 'Listings 96.001, 96.002, and 96.004 are retained for reconciliation '
    || 'and provenance but are not additive when SSA OASDI is represented.',
    'ANALYSIS-174B-5L-v1',
    2020,
    2024
FROM (
    VALUES
        ('96.001'),
        ('96.002'),
        ('96.004')
) AS programs(program_code)
CROSS JOIN (
    SELECT federal_inflow_source_policy_id
    FROM reference.federal_inflow_source_policy
    WHERE inflow_family = 'SOCIAL_SECURITY'
      AND inflow_subfamily = 'OASDI'
      AND methodology_version = 'ANALYSIS-116-v1'
) AS policy
ON CONFLICT (
    source_system,
    source_program_code,
    methodology_version
)

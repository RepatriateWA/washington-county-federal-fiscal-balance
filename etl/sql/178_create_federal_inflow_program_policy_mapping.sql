DECLARE
    v_total integer;
    v_exclude integer;
    v_include integer;
    v_withhold integer;
BEGIN

    SELECT
        COUNT(*),
        COUNT(*) FILTER (
            WHERE resolved_accounting_disposition = 'EXCLUDE_DUPLICATE'
        ),
        COUNT(*) FILTER (
            WHERE resolved_accounting_disposition = 'INCLUDE_ADDITIVE'
        ),
        COUNT(*) FILTER (
            WHERE resolved_accounting_disposition = 'WITHHOLD_UNRESOLVED'
        )
    INTO
        v_total,
        v_exclude,
        v_include,
        v_withhold
    FROM reference.federal_inflow_program_policy_mapping
    WHERE source_system = 'USASPENDING_ASSISTANCE'
      AND methodology_version = 'ANALYSIS-174B-5L-v1';

    IF v_total <> 12 THEN
    RAISE EXCEPTION
        'Expected 12 ETL-174B-5L program-policy mappings; found %',
        v_total;
    END IF;

    IF v_exclude <> 7 THEN
    RAISE EXCEPTION
        'Expected 7 EXCLUDE_DUPLICATE mappings; found %',
        v_exclude;
    END IF;

    IF v_include <> 2 THEN
        RAISE EXCEPTION
            'Expected 2 INCLUDE_ADDITIVE mappings; found %',
            v_include;
    END IF;

    IF v_withhold <> 3 THEN
        RAISE EXCEPTION
            'Expected 3 WITHHOLD_UNRESOLVED mappings; found %',
            v_withhold;
    END IF;

    RAISE NOTICE
        'PASS mapping inventory: total %, exclude %, include %, withhold %',
        v_total,
        v_exclude,
        v_include,
        v_withhold;

END
$$;


/* ============================================================================
   SECTION 10
   DISPLAY PERSISTED MAPPINGS
   ========================================================================== */

SELECT
    m.source_program_code,
    p.inflow_family,
    p.inflow_subfamily,
    p.ledger_treatment AS source_policy_treatment,
    m.resolved_accounting_disposition,
    p.preferred_source,
    p.methodology_version AS source_policy_methodology,
    m.methodology_version AS mapping_methodology,
    m.valid_from_fiscal_year,
    m.valid_through_fiscal_year
FROM reference.federal_inflow_program_policy_mapping AS m
JOIN reference.federal_inflow_source_policy AS p
  ON p.federal_inflow_source_policy_id =
     m.federal_inflow_source_policy_id
WHERE m.source_system = 'USASPENDING_ASSISTANCE'
  AND m.methodology_version = 'ANALYSIS-174B-5L-v1'
ORDER BY m.source_program_code;


/* ============================================================================
   SECTION 11
   VERIFY NO CHIP OR VA BLANKET MAPPING WAS CREATED
   ========================================================================== */

DO $$
DECLARE
    v_chip integer;
    v_va integer;
BEGIN

    SELECT COUNT(*)
    INTO v_chip
    FROM reference.federal_inflow_program_policy_mapping
    WHERE source_system = 'USASPENDING_ASSISTANCE'
      AND methodology_version = 'ANALYSIS-174B-5L-v1'
      AND source_program_code = '93.767';

    IF v_chip <> 0 THEN
        RAISE EXCEPTION
            'Unexpected blanket CHIP 93.767 program mapping found';
    END IF;

    SELECT COUNT(*)
    INTO v_va
    FROM reference.federal_inflow_program_policy_mapping
    WHERE source_system = 'USASPENDING_ASSISTANCE'
      AND methodology_version = 'ANALYSIS-174B-5L-v1'
      AND source_program_code LIKE '64.%';

    IF v_va <> 0 THEN
        RAISE EXCEPTION
            'Unexpected blanket VA 64.* program mapping found';
    END IF;

    RAISE NOTICE
        'PASS: CHIP remains award-specific; no blanket VA assistance mapping created';

END
$$;



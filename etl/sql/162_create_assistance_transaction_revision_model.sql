-- ETL-162
-- USAspending Assistance transaction revision model
--
-- Purpose:
--   1. Preserve assistance.award_transaction as the stable first-seen
--      canonical fiscal-event anchor.
--   2. Preserve every downloaded source observation immutably in
--      assistance.raw_award_transaction.
--   3. Record later source-observation differences explicitly instead of
--      silently overwriting canonical transaction values.
--   4. Keep protected fiscal-event fields under a hard conflict gate.
--
-- Policy version: ANALYSIS-162-v1

BEGIN;

CREATE TABLE IF NOT EXISTS assistance.transaction_field_policy (
    field_name text PRIMARY KEY,
    field_class text NOT NULL,
    policy_version text NOT NULL,
    rationale text NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT transaction_field_policy_class_chk
        CHECK (
            field_class IN (
                'PROTECTED_STABLE',
                'REVISABLE_ECONOMIC',
                'AWARD_SNAPSHOT',
                'MUTABLE_AWARD_METADATA',
                'PUBLICATION_METADATA'
            )
        )
);

COMMENT ON TABLE assistance.transaction_field_policy IS
'Explicit field-level policy for USAspending Assistance transaction normalization. ANALYSIS-162-v1 distinguishes protected fiscal-event content from revisable economic content, award snapshots, mutable award metadata, and publication metadata.';

CREATE TABLE IF NOT EXISTS assistance.award_transaction_revision (
    award_transaction_revision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    assistance_transaction_id bigint NOT NULL
        REFERENCES assistance.award_transaction (
            assistance_transaction_id
        ),

    raw_assistance_transaction_id bigint NOT NULL
        REFERENCES assistance.raw_award_transaction (
            raw_assistance_transaction_id
        ),

    field_name text NOT NULL,

    revision_class text NOT NULL,

    canonical_first_seen_value_text text,
    observed_value_text text,

    policy_version text NOT NULL,

    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT award_transaction_revision_class_chk
        CHECK (
            revision_class IN (
                'REVISABLE_ECONOMIC',
                'AWARD_SNAPSHOT',
                'MUTABLE_AWARD_METADATA',
                'PUBLICATION_METADATA'
            )
        ),

    CONSTRAINT award_transaction_revision_observation_field_uq
        UNIQUE (
            raw_assistance_transaction_id,
            field_name
        )
);

CREATE INDEX IF NOT EXISTS
    idx_assistance_award_transaction_revision_transaction
ON assistance.award_transaction_revision (
    assistance_transaction_id
);

CREATE INDEX IF NOT EXISTS
    idx_assistance_award_transaction_revision_class
ON assistance.award_transaction_revision (
    revision_class
);

CREATE INDEX IF NOT EXISTS
    idx_assistance_award_transaction_revision_field
ON assistance.award_transaction_revision (
    field_name
);

COMMENT ON TABLE assistance.award_transaction_revision IS
'Explicit source-observation differences from the first-seen canonical Assistance transaction. Rows are additive provenance; canonical transaction values are not silently overwritten.';

COMMENT ON COLUMN assistance.award_transaction_revision.canonical_first_seen_value_text IS
'Value stored on the first-seen canonical assistance.award_transaction row. NULL represents SQL NULL.';

COMMENT ON COLUMN assistance.award_transaction_revision.observed_value_text IS
'Value observed in the linked immutable raw Assistance source observation. NULL represents SQL NULL.';


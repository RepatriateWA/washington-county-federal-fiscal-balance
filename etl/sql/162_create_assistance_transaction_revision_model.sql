CREATE OR REPLACE VIEW assistance.v_award_transaction_revision_detail AS
SELECT
    revision.award_transaction_revision_id,
    revision.assistance_transaction_id,
    transaction.assistance_transaction_unique_key,
    revision.raw_assistance_transaction_id,
    raw.load_batch_id AS observed_load_batch_id,
    raw.source_row_number AS observed_source_row_number,
    revision.field_name,
    revision.revision_class,
    revision.canonical_first_seen_value_text,
    revision.observed_value_text,
    revision.policy_version,
    revision.created_at
FROM assistance.award_transaction_revision AS revision
JOIN assistance.award_transaction AS transaction
  ON transaction.assistance_transaction_id
     = revision.assistance_transaction_id
JOIN assistance.raw_award_transaction AS raw
  ON raw.raw_assistance_transaction_id
     = revision.raw_assistance_transaction_id;

COMMENT ON VIEW assistance.v_award_transaction_revision_detail IS
'Human-readable Assistance transaction revision provenance, including source load batch and source row.';

COMMIT;

-- Migration 111
-- Create canonical procurement place dimension.
--
-- Project: Washington County Federal Fiscal Balance
-- ETL: ETL-004A.3F
--
-- This table is intentionally separate from
-- procurement.place_of_performance, which is the one-row-per-award-transaction
-- relationship table.

BEGIN;

CREATE SCHEMA IF NOT EXISTS procurement;

CREATE TABLE IF NOT EXISTS procurement.place (
    place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    country_code VARCHAR(3),
    country_name VARCHAR(100),

    state_code VARCHAR(2),
    state_name VARCHAR(100),
    state_fips CHAR(2),

    county_name VARCHAR(100),
    county_fips CHAR(5),

    city_name VARCHAR(100),
    zip4 VARCHAR(9),

    congressional_district_current VARCHAR(10),
    congressional_district_original VARCHAR(10),

    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_procurement_place_country_code
        CHECK (country_code IS NULL OR country_code ~ '^[A-Z]{3}$'),

    CONSTRAINT ck_procurement_place_state_code
        CHECK (state_code IS NULL OR state_code ~ '^[A-Z]{2}$'),

    CONSTRAINT ck_procurement_place_state_fips
        CHECK (state_fips IS NULL OR state_fips ~ '^[0-9]{2}$'),

    CONSTRAINT ck_procurement_place_county_fips
        CHECK (county_fips IS NULL OR county_fips ~ '^[0-9]{5}$'),

    CONSTRAINT ck_procurement_place_county_state_consistency
        CHECK (
            county_fips IS NULL
            OR state_fips IS NULL
            OR LEFT(county_fips, 2) = state_fips
        ),

    CONSTRAINT ck_procurement_place_zip4
        CHECK (zip4 IS NULL OR zip4 ~ '^[0-9]{5}([0-9]{4})?$'),

    CONSTRAINT ck_procurement_place_cd_current
        CHECK (
            congressional_district_current IS NULL
            OR congressional_district_current ~ '^[A-Z]{2}-(AL|[0-9]{1,2})$'
        ),

    CONSTRAINT ck_procurement_place_cd_original
        CHECK (
            congressional_district_original IS NULL
            OR congressional_district_original ~ '^[A-Z]{2}-(AL|[0-9]{1,2})$'
        ),

    CONSTRAINT uq_procurement_place_identity
        UNIQUE NULLS NOT DISTINCT (
            country_code,
            state_fips,
            county_fips,
            city_name,
            zip4
        )
);

CREATE INDEX IF NOT EXISTS idx_procurement_place_state_fips
    ON procurement.place (state_fips);

CREATE INDEX IF NOT EXISTS idx_procurement_place_county_fips
    ON procurement.place (county_fips);

CREATE INDEX IF NOT EXISTS idx_procurement_place_state_county
    ON procurement.place (state_fips, county_fips);

CREATE INDEX IF NOT EXISTS idx_procurement_place_zip4
    ON procurement.place (zip4);

CREATE INDEX IF NOT EXISTS idx_procurement_place_cd_current
    ON procurement.place (congressional_district_current);

COMMENT ON TABLE procurement.place IS
    'Canonical geographic places reported by USAspending, separate from the transaction-level place_of_performance relationship.';

COMMENT ON COLUMN procurement.place.state_fips IS
    'Two-digit state FIPS from prime_award_transaction_place_of_performance_state_fips_code.';

COMMENT ON COLUMN procurement.place.county_fips IS
    'Five-digit county FIPS from prime_award_transaction_place_of_performance_county_fips_code.';

COMMENT ON COLUMN procurement.place.zip4 IS
    'USAspending primary_place_of_performance_zip_4 stored as text to preserve leading zeroes.';

COMMENT ON COLUMN procurement.place.congressional_district_current IS
    'Current congressional district attribute; excluded from canonical place identity because district boundaries change.';

COMMENT ON COLUMN procurement.place.congressional_district_original IS
    'Original congressional district attribute retained for historical traceability.';

COMMIT;